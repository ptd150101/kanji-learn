const canon = value => String(value ?? "")
  .normalize("NFKC")
  .replace(/[~～]/g, "〜")
  .trim();

test("N5 covers all 128 JLPT 2010-2024 PDF entries with the source reading", () => {
  assert.equal(source128.length, 128);
  const byWord = new Map(data.vocab.map(item => [canon(item.word), item]));

  for (const [word, reading] of source128) {
    const item = byWord.get(canon(word));
    assert.ok(item, `Thiếu từ nguồn PDF: ${word}`);
    const accepted = [item.reading, ...(item.accepted || [])].map(canon);
    assert.ok(accepted.includes(canon(reading)), `Sai cách đọc ${word}: cần ${reading}, hiện có ${item.reading}`);
  }
});

test("các theme N5 bổ sung từ PDF không vượt quá 20 mục", () => {
  const expected = new Map([[35,14],[36,14],[37,16],[38,6]]);
  for (const [lesson, count] of expected) {
    const rows = data.vocab.filter(item => item.lesson === lesson);
    assert.equal(rows.length, count, `Sai số lượng bài ${lesson}`);
    assert.ok(rows.length <= 20, `Bài ${lesson} vượt quá 20 mục`);
  }
});
